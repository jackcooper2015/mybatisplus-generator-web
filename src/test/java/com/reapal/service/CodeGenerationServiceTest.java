package com.reapal.service;

import com.reapal.model.DbConfig;
import com.reapal.model.TableStrategyConfig;
import com.reapal.model.Template;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.CompletableFuture;
import java.util.zip.ZipInputStream;

import static org.junit.jupiter.api.Assertions.*;

class CodeGenerationServiceTest {
    private final CodeGenerationService generator = new CodeGenerationService();
    private DbConfig database;

    @BeforeEach
    void createDisposableDatabase() throws Exception {
        database = new DbConfig();
        database.setUrl("jdbc:h2:mem:generator_" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
        database.setDriver("org.h2.Driver");
        database.setUsername("sa");
        database.setPassword("");
        try (var connection = DriverManager.getConnection(database.getUrl(), "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("create table t_account (id bigint generated by default as identity primary key, display_name varchar(80), created_at timestamp, is_delete int)");
            statement.execute("create table t_invoice (id bigint primary key, amount decimal(12,2))");
        }
    }

    @Test
    void generatesAllNineArtifactsAndModernEntityMetadata() throws Exception {
        Map<String, String> files = unzip(generator.generateZip(database, options("t_account"), List.of()));
        assertEquals(9, files.size(), files.keySet().toString());
        String entity = files.get("com/example/entity/Account.java");
        assertNotNull(entity);
        assertTrue(entity.contains("class Account extends Model<Account>"), entity);
        assertTrue(entity.contains("OffsetDateTime createdAt"), entity);
        assertTrue(entity.contains("@TableLogic"), entity);
        assertTrue(entity.contains("IdType.AUTO"), entity);
        assertTrue(files.get("com/example/mapper/xml/AccountMapper.xml").contains("namespace=\"com.example.mapper.AccountMapper\""));
        assertNotNull(files.get("resource/templates/views/t-account.html"));
        assertNotNull(files.get("resource/templates/views/t-account.vue"));
        assertNotNull(files.get("resource/static/js/t-account.js"));
        assertFalse(entity.contains("${"), entity);
    }

    @Test
    void generatedJavaCompilesAgainstCurrentDependencies() throws Exception {
        Map<String, String> files = unzip(generator.generateZip(database, options("t_account,t_invoice"), List.of()));
        var root = java.nio.file.Files.createTempDirectory("generated-java-test-");
        try {
            List<String> arguments = new java.util.ArrayList<>();
            arguments.addAll(List.of("--release", "17", "-classpath", System.getProperty("java.class.path"),
                    "-d", root.toString()));
            for (var entry : files.entrySet()) {
                if (!entry.getKey().endsWith(".java")) continue;
                var file = root.resolve(entry.getKey());
                java.nio.file.Files.createDirectories(file.getParent());
                java.nio.file.Files.writeString(file, entry.getValue());
                arguments.add(file.toString());
            }
            var diagnostics = new java.io.ByteArrayOutputStream();
            int result = javax.tools.ToolProvider.getSystemJavaCompiler().run(null, diagnostics, diagnostics,
                    arguments.toArray(new String[0]));
            assertEquals(0, result, diagnostics.toString(StandardCharsets.UTF_8));
        } finally {
            try (var paths = java.nio.file.Files.walk(root)) {
                for (var path : paths.sorted(java.util.Comparator.reverseOrder()).toList()) {
                    java.nio.file.Files.deleteIfExists(path);
                }
            }
        }
    }

    @Test
    void missingTableFailsInsteadOfReturningPartialArchive() {
        assertThrows(IllegalArgumentException.class,
                () -> generator.generateZip(database, options("t_account,missing_table"), List.of()));
    }

    @Test
    void batchGenerationHonorsNamingAndCustomTemplatesWithFallback() throws Exception {
        TableStrategyConfig config = options(" t_account , t_invoice ");
        config.setControllerName("%sResource");
        Template custom = new Template();
        custom.setTemplateName("page.js.vm");
        custom.setContent("// 中文 ${entity}; custom=${cfg.entityLombokModel}");
        Map<String, String> files = unzip(generator.generateZip(database, config, List.of(custom)));
        assertEquals(18, files.size());
        assertEquals("// 中文 Account; custom=true", files.get("resource/static/js/t-account.js"));
        assertEquals("// 中文 Invoice; custom=true", files.get("resource/static/js/t-invoice.js"));
        assertNotNull(files.get("com/example/controller/AccountResource.java"));
        assertNotNull(files.get("com/example/entity/Invoice.java"));
    }

    @Test
    void rejectsPathTraversalEmptySelectionAndBatchNameCollisions() {
        TableStrategyConfig config = options("../secret");
        assertThrows(IllegalArgumentException.class, () -> generator.generateZip(database, config, List.of()));
        config.setTableName("");
        assertThrows(IllegalArgumentException.class, () -> generator.generateZip(database, config, List.of()));
        config.setTableName("t_account,t_invoice");
        config.setEntityName("SameName");
        assertThrows(IllegalArgumentException.class, () -> generator.generateZip(database, config, List.of()));
        config.setEntityName("%s");
        config.setEntityPackage("../../escape");
        assertThrows(IllegalArgumentException.class, () -> generator.generateZip(database, config, List.of()));
    }

    @Test
    void collidingTableNamesFailInsteadOfLosingArtifacts() throws Exception {
        try (var connection = DriverManager.getConnection(database.getUrl(), "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("create table account (id bigint primary key)");
        }
        assertThrows(RuntimeException.class,
                () -> generator.generateZip(database, options("t_account,account"), List.of()));
    }

    @Test
    void simultaneousRequestsDoNotLeakOutputs() throws Exception {
        var one = CompletableFuture.supplyAsync(() -> generate("t_account"));
        var two = CompletableFuture.supplyAsync(() -> generate("t_invoice"));
        Map<String, String> accounts = unzip(one.get());
        Map<String, String> invoices = unzip(two.get());
        assertEquals(9, accounts.size());
        assertEquals(9, invoices.size());
        assertTrue(accounts.keySet().stream().noneMatch(name -> name.contains("Invoice")));
        assertTrue(invoices.keySet().stream().noneMatch(name -> name.contains("Account")));
    }

    private byte[] generate(String table) {
        try { return generator.generateZip(database, options(table), List.of()); }
        catch (Exception e) { throw new RuntimeException(e); }
    }

    private TableStrategyConfig options(String tables) {
        TableStrategyConfig config = new TableStrategyConfig();
        config.setTableName(tables);
        config.setPrefix("t_");
        config.setModelName("example");
        config.setAuthor("test");
        config.setServiceName("%sService");
        return config;
    }

    private Map<String, String> unzip(byte[] archive) throws Exception {
        Map<String, String> entries = new HashMap<>();
        try (ZipInputStream zip = new ZipInputStream(new ByteArrayInputStream(archive))) {
            for (var entry = zip.getNextEntry(); entry != null; entry = zip.getNextEntry()) {
                assertFalse(entry.getName().startsWith("/"));
                assertFalse(entry.getName().contains(".."));
                assertNull(entries.put(entry.getName(), new String(zip.readAllBytes(), StandardCharsets.UTF_8)));
            }
        }
        return entries;
    }
}
