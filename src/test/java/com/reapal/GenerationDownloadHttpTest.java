package com.reapal;

import com.reapal.dao.DbConfigDao;
import com.reapal.dao.TableStrategyConfigDao;
import com.reapal.model.DbConfig;
import com.reapal.model.TableStrategyConfig;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;

import java.io.ByteArrayInputStream;
import java.net.CookieManager;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;
import java.util.zip.ZipInputStream;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT, properties = {
        "spring.datasource.url=jdbc:h2:mem:runtime-test;MODE=MYSQL;DB_CLOSE_DELAY=-1",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.jpa.hibernate.ddl-auto=create-drop",
        "generator.admin.username=admin",
        "generator.admin.password=test-only-password"
})
class GenerationDownloadHttpTest {
    @LocalServerPort
    private int port;
    @Autowired
    private DbConfigDao databases;
    @Autowired
    private TableStrategyConfigDao strategies;

    @Test
    void singleAndBatchRoutesDownloadCompleteSafeArchives() throws Exception {
        String databaseUrl = "jdbc:h2:mem:http_generator_" + UUID.randomUUID()
                + ";DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE";
        Long databaseId = null;
        Long strategyId = null;
        try (var connection = DriverManager.getConnection(databaseUrl, "sa", "")) {
            try (var statement = connection.createStatement()) {
                statement.execute("create table t_customer (id bigint generated by default as identity primary key, display_name varchar(80))");
                statement.execute("create table t_purchase (id bigint generated by default as identity primary key, display_name varchar(80))");
            }
            try {
                DbConfig database = new DbConfig();
                database.setDbName("Disposable HTTP generator test");
                database.setUrl(databaseUrl);
                database.setDriver("org.h2.Driver");
                database.setUsername("sa");
                database.setPassword("");
                databaseId = databases.saveAndFlush(database).getId();

                TableStrategyConfig strategy = new TableStrategyConfig();
                strategy.setDbId(databaseId);
                strategy.setTableName("t_customer");
                strategy.setPrefix("t_");
                strategy.setModelName("httpfixture");
                strategyId = strategies.saveAndFlush(strategy).getId();

                HttpClient client = HttpClient.newBuilder().cookieHandler(new CookieManager()).build();
                HttpResponse<String> login = client.send(HttpRequest.newBuilder(uri("/login"))
                        .header("Content-Type", "application/x-www-form-urlencoded")
                        .POST(HttpRequest.BodyPublishers.ofString("username=admin&password=test-only-password"))
                        .build(), HttpResponse.BodyHandlers.ofString());
                assertEquals(200, login.statusCode());
                assertEquals("true", login.body());

                Set<String> single = download(client, "/generate?tableName=t_customer&id=" + databaseId, 9);
                assertTrue(single.contains("com/httpfixture/entity/Customer.java"), single.toString());
                assertTrue(single.contains("resource/static/js/t-customer.js"), single.toString());

                String options = "{\"tableName\":\"t_customer,t_purchase\",\"prefix\":\"t_\",\"modelName\":\"httpfixture\"}";
                Set<String> batch = download(client, "/batchGenerate?jsonStr="
                        + URLEncoder.encode(options, StandardCharsets.UTF_8) + "&id=" + databaseId, 18);
                assertTrue(batch.containsAll(single), batch.toString());
                assertTrue(batch.contains("com/httpfixture/entity/Purchase.java"), batch.toString());
                assertTrue(batch.contains("resource/static/js/t-purchase.js"), batch.toString());
            } finally {
                if (strategyId != null) strategies.deleteById(strategyId);
                if (databaseId != null) databases.deleteById(databaseId);
                try (var statement = connection.createStatement()) {
                    statement.execute("DROP ALL OBJECTS");
                    statement.execute("SET DB_CLOSE_DELAY 0");
                }
            }
        }
    }

    private Set<String> download(HttpClient client, String route, int expectedFiles) throws Exception {
        HttpResponse<byte[]> response = client.send(HttpRequest.newBuilder(uri(route)).GET().build(),
                HttpResponse.BodyHandlers.ofByteArray());
        assertEquals(200, response.statusCode(), new String(response.body(), StandardCharsets.UTF_8));
        assertEquals("application/zip", response.headers().firstValue("content-type").orElseThrow());
        assertEquals("attachment; filename=src.zip", response.headers().firstValue("content-disposition").orElseThrow());
        Set<String> names = new HashSet<>();
        try (ZipInputStream zip = new ZipInputStream(new ByteArrayInputStream(response.body()))) {
            for (var entry = zip.getNextEntry(); entry != null; entry = zip.getNextEntry()) {
                String name = entry.getName();
                assertFalse(entry.isDirectory());
                assertFalse(name.startsWith("/"), name);
                assertFalse(name.contains("\\"), name);
                assertFalse(name.contains(":"), name);
                assertFalse(java.util.Arrays.asList(name.split("/")).contains(".."), name);
                assertTrue(names.add(name), "Duplicate ZIP entry: " + name);
                assertTrue(zip.readAllBytes().length > 0, "Empty ZIP entry: " + name);
            }
        }
        assertEquals(expectedFiles, names.size(), names.toString());
        return names;
    }

    private URI uri(String route) {
        return URI.create("http://127.0.0.1:" + port + route);
    }
}
